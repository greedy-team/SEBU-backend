-- Stop on missing/ambiguous identities, including NULL-email professors and soft-deleted labs.
INSERT INTO v45_field_guard
SELECT 'professor identity missing or ambiguous', COUNT(*) FROM v45_reviewed_lab s
WHERE (SELECT COUNT(*) FROM professor p
    JOIN department d ON d.id=p.department_id JOIN college c ON c.id=d.college_id
    WHERE (s.email IS NOT NULL AND p.email=s.email)
       OR (s.email IS NULL AND p.email IS NULL AND p.name=s.professor_name
           AND d.name=s.department_name AND c.name=s.college_name)) <> 1;

UPDATE v45_reviewed_lab SET professor_id = (
    SELECT p.id FROM professor p
    JOIN department d ON d.id=p.department_id JOIN college c ON c.id=d.college_id
    WHERE (v45_reviewed_lab.email IS NOT NULL AND p.email=v45_reviewed_lab.email)
       OR (v45_reviewed_lab.email IS NULL AND p.email IS NULL
           AND p.name=v45_reviewed_lab.professor_name
           AND d.name=v45_reviewed_lab.department_name AND c.name=v45_reviewed_lab.college_name)
);

INSERT INTO v45_field_guard
SELECT 'professor email belongs to a different name', COUNT(*)
FROM v45_reviewed_lab s JOIN professor p ON p.id=s.professor_id
WHERE CAST(p.name AS BINARY(400)) <> CAST(s.professor_name AS BINARY(400));

INSERT INTO v45_field_guard
SELECT 'active laboratory missing or ambiguous', COUNT(*) FROM v45_reviewed_lab s
WHERE (SELECT COUNT(*) FROM laboratory l WHERE l.professor_id=s.professor_id AND l.deleted_at IS NULL) <> 1;

UPDATE v45_reviewed_lab SET laboratory_id = (
    SELECT l.id FROM laboratory l WHERE l.professor_id=v45_reviewed_lab.professor_id AND l.deleted_at IS NULL
);

