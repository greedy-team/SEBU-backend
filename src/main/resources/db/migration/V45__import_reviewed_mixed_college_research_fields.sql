CREATE TABLE v45_new_category (
    category_order INT NOT NULL,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NOT NULL,
    CONSTRAINT pk_v45_new_category PRIMARY KEY (code),
    CONSTRAINT uk_v45_new_category_name UNIQUE (name)
);
CREATE TABLE v45_reviewed_lab (
    record_key INT NOT NULL,
    college_name VARCHAR(100) NOT NULL,
    department_name VARCHAR(100) NOT NULL,
    professor_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NULL,
    professor_id BIGINT NULL,
    laboratory_id BIGINT NULL,
    CONSTRAINT pk_v45_reviewed_lab PRIMARY KEY (record_key)
);
CREATE TABLE v45_reviewed_field (
    field_key INT NOT NULL,
    name VARCHAR(100) NOT NULL,
    research_field_id BIGINT NULL,
    CONSTRAINT pk_v45_reviewed_field PRIMARY KEY (field_key),
    CONSTRAINT uk_v45_reviewed_field_name UNIQUE (name)
);
CREATE TABLE v45_lab_field (
    record_key INT NOT NULL,
    field_key INT NOT NULL,
    CONSTRAINT pk_v45_lab_field PRIMARY KEY (record_key, field_key)
);
CREATE TABLE v45_field_category (
    field_key INT NOT NULL,
    category_code VARCHAR(50) NOT NULL,
    CONSTRAINT pk_v45_field_category PRIMARY KEY (field_key, category_code)
);
CREATE TABLE v45_field_guard (
    reason VARCHAR(100) NOT NULL,
    violations INT NOT NULL,
    CONSTRAINT ck_v45_field_no_conflicts CHECK (violations = 0)
);

